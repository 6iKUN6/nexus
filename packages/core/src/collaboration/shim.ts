import { chmodSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';

/**
 * Writes the `nexus-helper` launcher (D14). Harnesses that have no MCP support
 * (pi) get a plain command they can run from a shell, so the launcher must be
 * a real executable file rather than a JS path only Electron can start.
 *
 * The runner is injected by the desktop shell: inside the app the helper is a
 * JS bundle and the runner is Electron-as-Node, while tests can pass `node`.
 * The file contains paths only — socket and token come from the environment.
 */
export function writeHelperShim(
  shimPath: string,
  runner: {
    command: string;
    args?: string[] | undefined;
    env?: Record<string, string> | undefined;
  },
  helperScript: string,
): void {
  const quote = (value: string) => `'${value.replace(/'/g, `'\\''`)}'`;
  const envPrefix = Object.entries(runner.env ?? {})
    .map(([key, value]) => `${key}=${quote(value)}`)
    .join(' ');
  const argv = [...(runner.args ?? []).map(quote), quote(helperScript), '"$@"'].join(' ');
  const line = [envPrefix, 'exec', quote(runner.command), argv].filter(Boolean).join(' ');
  mkdirSync(dirname(shimPath), { recursive: true, mode: 0o700 });
  writeFileSync(
    shimPath,
    `#!/bin/sh\n# Generated by Nexus (D14). Do not edit; it is rewritten on every start.\n${line}\n`,
    { mode: 0o755 },
  );
  chmodSync(shimPath, 0o755);
}
