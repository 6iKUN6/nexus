import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import {
  type CollaborationTool,
  collaborationToolSchema,
  collaborationTools,
} from '@nexus/protocol';

/**
 * Generates the pi bridge extension (D23, ADR 0020): a TypeScript module
 * loaded with `pi -e <path>` that registers the six collaboration tools
 * (D14, ADR 0016) natively, instead of asking the agent to run the one-shot
 * helper from a shell. pi loads extensions with jiti, so the file needs no
 * compilation; tool definitions are rendered from the protocol schemas so
 * bridge, helper and socket server cannot drift apart.
 *
 * Like the helper, the bridge is stateless: every tool call opens the local
 * socket, authenticates with the per-session token from the environment and
 * forwards one JSON-RPC request. A failure throws inside `execute`, which pi
 * reports to the model with `isError: true` — the same semantics as the
 * helper's MCP server.
 */

/** pi expects a typebox-shaped schema; a plain JSON-schema literal qualifies. */
function parametersFor(tool: CollaborationTool): Record<string, unknown> {
  const schema = collaborationToolSchema(tool);
  // The $schema dialect marker means nothing to typebox consumers.
  const { $schema: _dropped, ...rest } = schema;
  return rest;
}

function bridgeSource(): string {
  const tools = (Object.keys(collaborationTools) as CollaborationTool[]).map((name) => ({
    name,
    label: name,
    description: collaborationTools[name].description,
    parameters: parametersFor(name),
  }));
  return `// Generated by Nexus (D14/D23). Do not edit; it is rewritten on every start.
import { connect } from 'node:net';

const TOOLS = ${JSON.stringify(tools, null, 2)};

function callCore(method, params) {
  const socketPath = process.env.NEXUS_SOCKET;
  const token = process.env.NEXUS_TOKEN;
  if (!socketPath || !token) {
    return Promise.reject(new Error('协作通道未配置（缺少 NEXUS_SOCKET / NEXUS_TOKEN）'));
  }
  return new Promise((resolve, reject) => {
    const socket = connect(socketPath);
    let buffer = '';
    const finish = (fn, value) => {
      socket.destroy();
      fn(value);
    };
    const fail = (message) => finish(reject, new Error(message));
    socket.setEncoding('utf8');
    socket.setTimeout(15_000, () => fail('协作通道响应超时'));
    socket.once('error', (error) => fail(\`无法连接 Nexus：\${error.message}\`));
    socket.once('close', () => fail('协作通道连接已关闭'));
    socket.once('connect', () => {
      socket.write(\`\${JSON.stringify({ jsonrpc: '2.0', id: 1, method: 'auth', params: { token } })}\\n\`);
    });
    socket.on('data', (chunk) => {
      buffer += chunk;
      for (;;) {
        const newline = buffer.indexOf('\\n');
        if (newline < 0) return;
        const line = buffer.slice(0, newline).trim();
        buffer = buffer.slice(newline + 1);
        if (!line) continue;
        let message;
        try {
          message = JSON.parse(line);
        } catch {
          continue;
        }
        if (message.id === 1) {
          if (message.error) return fail(String(message.error.message ?? '认证失败'));
          socket.write(\`\${JSON.stringify({ jsonrpc: '2.0', id: 2, method, params })}\\n\`);
        } else if (message.id === 2) {
          if (message.error) return fail(String(message.error.message ?? '未知错误'));
          return finish(resolve, message.result);
        }
      }
    });
  });
}

export default function (pi) {
  for (const tool of TOOLS) {
    pi.registerTool({
      name: tool.name,
      label: tool.label,
      description: tool.description,
      parameters: tool.parameters,
      // Defaults declared in the schema (e.g. send_message.to) are applied
      // server-side too, so params pass through untouched.
      execute: async (_toolCallId, params) => {
        const result = await callCore(\`collab.\${tool.name}\`, params ?? {});
        return { content: [{ type: 'text', text: JSON.stringify(result) }], details: {} };
      },
    });
  }
}
`;
}

/** Writes (or refreshes) the bridge extension and returns its absolute path. */
export function writePiBridge(dir: string): string {
  mkdirSync(dir, { recursive: true, mode: 0o700 });
  const path = join(dir, 'nexus-bridge.ts');
  writeFileSync(path, bridgeSource(), { mode: 0o600 });
  return path;
}
